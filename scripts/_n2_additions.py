def blk(label, lines):
    """Build blocks: label header + one or more line entries."""
    out = [{"t":"label","label":label,"text":""}]
    for ln in lines:
        out.append({"t":"line","text":ln})
    return out

def point(num, title, blocks):
    return {"title": f"{num}. {title}", "blocks": blocks}


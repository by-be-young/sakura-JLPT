def apply_fix(s):
    for a, b in WORD_FIX.items():
        if a in s:
            s = s.replace(a, b)
    for a, b in CHAR_FIX.items():
        if a in s:
            s = s.replace(a, b)
    return s

for lv in LEVELS:
    data = json.load(open(f'{lv}_kuro.json', encoding='utf-8'))
    fixed = 0
    for e in data:
        newk = apply_fix(e['kanji'])
        if newk != e['kanji']:
            e['kanji'] = newk
            fixed += 1
    with open(f'{lv}_fix.json', 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print(f'{lv}: 汉字修复 {fixed} / 总数 {len(data)}')
